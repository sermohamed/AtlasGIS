#!/usr/bin/env node
/**
 * Embeds crs/data/*.json into crs/atlas-crs.data.js so the browser can boot
 * the registry synchronously (no fetch race on GitHub Pages / file://).
 * Re-run after editing any JSON under crs/data/.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const dataDir = path.join(root, 'crs', 'data');
const outFile = path.join(root, 'crs', 'atlas-crs.data.js');

const seed = JSON.parse(fs.readFileSync(path.join(dataDir, 'seed.json'), 'utf8'));
const countries = JSON.parse(fs.readFileSync(path.join(dataDir, 'countries.json'), 'utf8'));
const countryCrs = JSON.parse(fs.readFileSync(path.join(dataDir, 'country_crs.json'), 'utf8'));

const banner = `/* AUTO-GENERATED by tools/embed-crs-data.js — do not edit by hand.
 * Source of truth: crs/data/{seed,countries,country_crs}.json
 */
`;

const body = `${banner}(function (global) {
  'use strict';
  global.__ATLAS_CRS_DATA__ = ${JSON.stringify({ seed, countries, countryCrs }, null, 2)};
})(typeof window !== 'undefined' ? window : globalThis);
`;

fs.writeFileSync(outFile, body);
console.log('wrote', path.relative(root, outFile),
  `(${seed.length} CRS, ${countries.length} countries, ${countryCrs.length} links)`);
